static HAL_StatusTypeDef OV5640_ReadReg(uint16_t reg, uint8_t *value)
{
  return HAL_I2C_Mem_Read(&hi2c1, OV5640_I2C_ADDRESS, reg,
                          I2C_MEMADD_SIZE_16BIT, value, 1U, 100U);
}

static HAL_StatusTypeDef OV5640_WriteReg(uint16_t reg, uint8_t value)
{
  return HAL_I2C_Mem_Write(&hi2c1, OV5640_I2C_ADDRESS, reg,
                           I2C_MEMADD_SIZE_16BIT, &value, 1U, 100U);
}

static HAL_StatusTypeDef OV5640_WriteTable(const OV5640_RegValueTypeDef *table,
                                           uint32_t length)
{
  uint32_t index;
  HAL_StatusTypeDef status;

  for (index = 0U; index < length; index++)
  {
    status = OV5640_WriteReg(table[index].reg, table[index].value);
    if (status != HAL_OK)
    {
      return status;
    }
    if ((table[index].reg == 0x3008U) && (table[index].value == 0x82U))
    {
      HAL_Delay(5U);
    }
  }

  return HAL_OK;
}

HAL_StatusTypeDef OV5640_Probe(volatile uint16_t *sensor_id)
{
  uint8_t id_high = 0U;
  uint8_t id_low = 0U;
  HAL_StatusTypeDef status;

  /* PWDN 拉低表示工作；RESET 产生低电平复位脉冲。 */
  HAL_GPIO_WritePin(CAM_PWDN_GPIO_Port, CAM_PWDN_Pin, GPIO_PIN_RESET);
  HAL_GPIO_WritePin(CAM_RESET_GPIO_Port, CAM_RESET_Pin, GPIO_PIN_RESET);
  HAL_Delay(5U);
  HAL_GPIO_WritePin(CAM_RESET_GPIO_Port, CAM_RESET_Pin, GPIO_PIN_SET);
  HAL_Delay(20U);

  status = OV5640_ReadReg(0x300AU, &id_high);
  if (status != HAL_OK)
  {
    return status;
  }

  status = OV5640_ReadReg(0x300BU, &id_low);
  if (status != HAL_OK)
  {
    return status;
  }

  *sensor_id = ((uint16_t)id_high << 8) | id_low;
  return HAL_OK;
}

HAL_StatusTypeDef OV5640_ConfigRGB565VGA(void)
{
  HAL_StatusTypeDef status;

  status = OV5640_WriteTable(ov5640_rgb565_common,
                              sizeof(ov5640_rgb565_common) / sizeof(ov5640_rgb565_common[0]));
  if (status != HAL_OK)
  {
    return status;
  }

  return OV5640_WriteTable(ov5640_rgb565_vga,
                            sizeof(ov5640_rgb565_vga) / sizeof(ov5640_rgb565_vga[0]));
}

HAL_StatusTypeDef OV5640_ConfigRGB565QVGA(void)
{
  HAL_StatusTypeDef status;

  status = OV5640_WriteTable(ov5640_rgb565_common,
                              sizeof(ov5640_rgb565_common) / sizeof(ov5640_rgb565_common[0]));
  if (status != HAL_OK)
  {
    return status;
  }

  status = OV5640_WriteTable(ov5640_rgb565_qvga,
                              sizeof(ov5640_rgb565_qvga) / sizeof(ov5640_rgb565_qvga[0]));
  if (status != HAL_OK)
  {
    return status;
  }

  /* 配置生效后读取关键寄存器，供 Keil Watch 验证。 */
  HAL_Delay(100U);
  status = OV5640_ReadReg(0x3008U, (uint8_t *)&ov5640_reg_3008);
  if (status != HAL_OK)
  {
    return status;
  }
  status = OV5640_ReadReg(0x3808U, (uint8_t *)&ov5640_reg_3808);
  if (status != HAL_OK)
  {
    return status;
  }
  status = OV5640_ReadReg(0x3809U, (uint8_t *)&ov5640_reg_3809);
  if (status != HAL_OK)
  {
    return status;
  }
  return OV5640_ReadReg(0x4300U, (uint8_t *)&ov5640_reg_4300);
}

HAL_StatusTypeDef OV5640_ConfigJPEGQVGA(void)
{
  HAL_StatusTypeDef status;
  ov5640_jpeg_config_step = 1U;
  status = OV5640_WriteTable(ov5640_rgb565_common, sizeof(ov5640_rgb565_common) / sizeof(ov5640_rgb565_common[0]));
  if (status != HAL_OK) return status;
  ov5640_jpeg_config_step = 2U;
  status = OV5640_WriteTable(ov5640_rgb565_qvga, sizeof(ov5640_rgb565_qvga) / sizeof(ov5640_rgb565_qvga[0]));
  if (status != HAL_OK) return status;
  ov5640_jpeg_config_step = 3U;
  status = OV5640_WriteTable(ov5640_jpeg_qvga_output, sizeof(ov5640_jpeg_qvga_output) / sizeof(ov5640_jpeg_qvga_output[0]));
  if (status != HAL_OK) return status;
  HAL_Delay(100U);
  status = OV5640_ReadReg(0x4300U, (uint8_t *)&ov5640_reg_4300);
  if (status != HAL_OK) return status;
  status = OV5640_ReadReg(0x501fU, (uint8_t *)&ov5640_reg_501f);
  if (status != HAL_OK) return status;
  status = OV5640_ReadReg(0x3821U, (uint8_t *)&ov5640_reg_3821);
  if (status != HAL_OK) return status;
  status = OV5640_ReadReg(0x3002U, (uint8_t *)&ov5640_reg_3002);
  if (status != HAL_OK) return status;
  status = OV5640_ReadReg(0x3006U, (uint8_t *)&ov5640_reg_3006);
  if (status == HAL_OK) ov5640_jpeg_config_step = 4U;
  return status;
}
